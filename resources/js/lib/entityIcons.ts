export function entityIcon(name: string | null | undefined): LucideIcon | null {
    return name ? (ENTITY_ICONS[name] ?? null) : null;
}

/** "Portivio Frontier" → "PF", "QA" → "Q", "reporting-redesign" → "RR". */
export function monogram(name: string): string {
    const parts = name.split(/[\s\-_/·]+/).filter(Boolean);

    if (parts.length === 0) {
        return '?';
    }

    if (parts.length === 1) {
        return parts[0].slice(0, 1).toUpperCase();
    }

    return `${parts[0][0]}${parts[1][0]}`.toUpperCase();
}
